#!/bin/sh
# Снимок всего экрана для живой проверки (инструмент разработчика).
# Использование: tools/screenshot.sh файл.png
# Старый файл удаляется заранее: если снимок не удастся, устаревшее
# изображение не будет принято за текущее.
rm -f "$1"
# Ограничение по времени: при сбое spectacle KDE открывает окно отчёта
# и процесс не завершается сам.
timeout -k 2 15 spectacle -b -n -f -o "$1" >/dev/null 2>&1
[ -s "$1" ] || { echo "Снимок не получен: $1" >&2; exit 1; }
# Размер снимка выводится для настройки EMULATE_SIZE помощника ввода.
python3 -c "import sys; from PIL import Image; w, h = Image.open(sys.argv[1]).size; print(f'{w}x{h}')" "$1"
